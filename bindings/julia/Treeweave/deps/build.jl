# deps/build.jl: locate libtreeweave_c via env var → sibling CMake build → GitHub Release download.
# No Artifacts.toml by design; build failure must not block precompilation.

using Libdl
using Downloads
using TOML

const LIBNAME = "libtreeweave_c." * Libdl.dlext

function find_in_build_tree(start::AbstractString)
    dir = abspath(start)
    while true
        for bd in sort(filter(isdir, readdir(dir; join = true)))
            if startswith(basename(bd), "build")
                cand = joinpath(bd, LIBNAME)
                isfile(cand) && return cand
            end
        end
        parent = dirname(dir)
        parent == dir && return nothing
        dir = parent
    end
end

# Map the host to the release asset suffix produced by .github/workflows/release.yml.
function host_asset_suffix()
    arch = String(Sys.ARCH)
    if Sys.islinux()
        arch == "x86_64" && return "linux-x86_64.tar.gz"
        arch in ("aarch64", "arm64") && return "linux-aarch64.tar.gz"
    elseif Sys.isapple()
        arch == "x86_64" && return "macos-x86_64.tar.gz"
        arch in ("aarch64", "arm64") && return "macos-arm64.tar.gz"
    elseif Sys.iswindows()
        arch == "x86_64" && return "windows-x64.zip"
    end
    return nothing
end

function unpack(archive::AbstractString, dir::AbstractString)
    if endswith(archive, ".zip")
        run(`unzip -q $archive -d $dir`)
    else
        run(`tar -xzf $archive -C $dir`)
    end
end

# Find libtreeweave_c.<ext> (or treeweave_c.dll) anywhere under `root`.
function find_lib(root::AbstractString)
    for (dir, _, files) in walkdir(root)
        for f in files
            (f == LIBNAME || f == "treeweave_c.dll") && return joinpath(dir, f)
        end
    end
    return nothing
end

function download_prebuilt()
    suffix = host_asset_suffix()
    suffix === nothing && return ""
    proj = TOML.parsefile(normpath(joinpath(@__DIR__, "..", "Project.toml")))
    ver = proj["version"]
    repo = get(ENV, "TREEWEAVE_REPO", "DiamonDinoia/treeweave")
    asset = "treeweave-$(ver)-$(suffix)"
    url = "https://github.com/$repo/releases/download/v$(ver)/$asset"
    dest = joinpath(@__DIR__, "usr")
    try
        @info "Treeweave build: downloading prebuilt libtreeweave_c" url
        ispath(dest) && rm(dest; recursive = true)
        mkpath(dest)
        archive = Downloads.download(url)
        try
            unpack(archive, dest)
        finally
            isfile(archive) && rm(archive)
        end
        lib = find_lib(dest)
        lib === nothing ? "" : lib
    catch err
        @warn "Treeweave build: prebuilt download failed; relying on env / sibling build" err
        ""
    end
end

function locate()
    env = get(ENV, "LIBTREEWEAVE_C", "")
    !isempty(env) && isfile(env) && return env
    walked = find_in_build_tree(@__DIR__)
    walked === nothing || return walked
    return download_prebuilt()
end

path = locate()

open(joinpath(@__DIR__, "deps.jl"), "w") do io
    println(io, "# Auto-generated by deps/build.jl. Do not edit.")
    println(io, "# The final expression is the resolved libtreeweave_c path,")
    println(io, "# so `include(\"deps.jl\")` returns it.")
    println(io, repr(path))
end

if isempty(path)
    @warn "Treeweave build: libtreeweave_c not found; set LIBTREEWEAVE_C or build the project."
else
    @info "Treeweave build: using libtreeweave_c at $path"
end
